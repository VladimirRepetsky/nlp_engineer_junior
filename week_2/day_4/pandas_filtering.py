import pandas as pd
from pathlib import Path


def print_section(title):
    """
    Вспомогательная функция для красивого вывода разделов.
    """
    print("\n" + "=" * 20 + f" {title} " + "=" * 20)


def create_sample_dataframe():
    """
    Создаёт небольшой учебный DataFrame с отзывами.
    """
    data = {
        "id": [1, 2, 3, 4, 5, 6],
        "review_text": [
            "Отличный товар рекомендую",
            "Так себе качество слабое",
            "Нормально за свою цену ок",
            "Очень понравилось буду заказывать ещё",
            "Ужасно не советую",
            "Супер качество доставка быстрая",
        ],
        "rating": [5, 2, 3, 4, 1, 5],
        "author": ["Анна", "Иван", "Мария", "Олег", "Света", "Петр"],
    }

    return pd.DataFrame(data)


if __name__ == "__main__":
    # Путь к CSV рядом со скриптом
    csv_path = Path(__file__).resolve().parent / "reviews.csv"

    # Если CSV ещё нет, создадим его
    if not csv_path.exists():
        df_to_save = create_sample_dataframe()
        df_to_save.to_csv(csv_path, index=False, encoding="utf-8")
        print("CSV создан:")
        print(csv_path)

    # Загружаем данные
    df = pd.read_csv(csv_path, encoding="utf-8")

    print_section("Исходный DataFrame")
    print(df)

    # =========================================================
    # 1. Выбор одного столбца
    # =========================================================
    print_section("1. Один столбец")

    print("Тип объекта:")
    print(type(df["rating"]))

    print("\nСам столбец:")
    print(df["rating"])

    # =========================================================
    # 2. Выбор нескольких столбцов
    # =========================================================
    print_section("2. Несколько столбцов")

    selected_columns = df[["review_text", "rating"]]

    print("Тип объекта:")
    print(type(selected_columns))

    print("\nВыбранные столбцы:")
    print(selected_columns)

    # =========================================================
    # 3. Логическая маска
    # =========================================================
    print_section("3. Логическая маска")

    mask = df["rating"] > 4

    print(mask)

    # =========================================================
    # 4. Фильтрация строк по условию
    # =========================================================
    print_section("4. Фильтрация по условию")

    high_rating = df[df["rating"] > 4]

    print("Отзывы с рейтингом выше 4:")
    print(high_rating)

    # =========================================================
    # 5. То же самое через .loc
    # =========================================================
    print_section("5. .loc с условием")

    high_rating_loc = df.loc[df["rating"] > 4]

    print(high_rating_loc)

    # =========================================================
    # 6. Главное задание дня:
    # выбрать отзывы с рейтингом выше 4
    # и оставить только review_text и rating
    # =========================================================
    print_section("6. Главное задание дня")

    result = df.loc[
        df["rating"] > 4,
        ["review_text", "rating"]
    ]

    print(result)

    # =========================================================
    # 7. Использование .iloc
    # =========================================================
    print_section("7. .iloc")

    print("Первые 3 строки:")
    print(df.iloc[0:3])

    print("\nПервые 3 строки и столбцы с позициями 1 и 2:")
    print(df.iloc[0:3, 1:3])

    print("\nВсе строки, но только столбцы с позициями 1 и 2:")
    print(df.iloc[:, 1:3])

    # =========================================================
    # 8. Несколько условий
    # =========================================================
    print_section("8. Несколько условий")

    print("Рейтинг больше или равен 4:")
    print(df[df["rating"] >= 4])

    print("\nРейтинг больше 4 и автор Анна:")
    print(df[(df["rating"] > 4) & (df["author"] == "Анна")])

    print("\nРейтинг меньше 3 или автор Мария:")
    print(df[(df["rating"] < 3) | (df["author"] == "Мария")])

    # =========================================================
    # 9. Добавление новой колонки через .loc
    # =========================================================
    print_section("9. Новая колонка через .loc")

    df.loc[df["rating"] > 4, "sentiment"] = "positive"
    df.loc[df["rating"] <= 4, "sentiment"] = "not_positive"

    print(df)

    # =========================================================
    # 10. Сохраняем результат
    # =========================================================
    print_section("10. Сохранение результата")

    output_path = Path(__file__).resolve().parent / "reviews_filtered.csv"

    result.to_csv(output_path, index=False, encoding="utf-8")

    print("Отфильтрованный результат сохранён сюда:")
    print(output_path)