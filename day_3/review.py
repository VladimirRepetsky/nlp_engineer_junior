"""
День 3: Основы ООП — Классы и Объекты
Файл: review.py

Здесь мы создаём класс Review, который описывает один отзыв пользователя.
Это наш первый шаг к объектно-ориентированному программированию (ООП).

Ключевые понятия дня:
- КЛАСС   -> "чертёж" (шаблон) объекта
- ОБЪЕКТ  -> конкретная вещь, созданная по чертежу
- АТРИБУТ -> данные объекта (text, rating, author)
- МЕТОД   -> действие, которое объект умеет делать (to_dict)
"""

import json
from pathlib import Path


# ============================================================
# КЛАСС — это "чертёж", по которому создаются объекты.
# Представь, что класс — это бланк анкеты отзыва,
# а объект — уже заполненная анкета конкретного человека.
# ============================================================
class Review:
    """Класс, представляющий один отзыв пользователя."""

    def __init__(self, text: str, rating: int, author: str):
        """
        КОНСТРУКТОР класса.
        Вызывается АВТОМАТИЧЕСКИ, когда мы пишем:
            Review("текст", 5, "Анна")

        :param text: текст отзыва
        :param rating: оценка от 1 до 5
        :param author: имя автора отзыва
        """
        # self — это ссылка на КОНКРЕТНЫЙ объект, который мы создаём.
        # self.text = text означает:
        # "сохрани переданный текст ВНУТРЬ этого объекта как его атрибут"
        self.text = text
        self.author = author

        # ИНКАПСУЛЯЦИЯ: объект сам защищает своё внутреннее состояние.
        # Мы проверяем рейтинг ПЕРЕД тем, как сохранить его.
        # Если данные некорректны — объект даже не будет создан.
        if not isinstance(rating, int):
            raise TypeError("Рейтинг должен быть целым числом")
        if not (1 <= rating <= 5):
            raise ValueError("Рейтинг должен быть в диапазоне от 1 до 5")

        self.rating = rating

    def to_dict(self) -> dict:
        """
        МЕТОД объекта. Превращает объект Review в обычный словарь.
        Это удобно для сохранения в JSON (привет из Дня 2!).
        """
        return {
            "text": self.text,
            "rating": self.rating,
            "author": self.author,
        }

    def __repr__(self) -> str:
        """
        Служебный метод. Определяет, как объект выглядит при печати.
        Без него мы бы видели нечитаемое:
            <__main__.Review object at 0x7f8b2c...>
        """
        return f"Review(author={self.author!r}, rating={self.rating}, text={self.text!r})"


# ============================================================
# Функция-помощник: сохраняет список объектов Review в JSON.
# Это мостик к знаниям из Дня 2.
# ============================================================
def save_reviews_to_json(reviews: list, filename: str = "reviews.json") -> None:
    """Сохраняет список объектов Review в JSON-файл рядом со скриптом."""
    # Превращаем каждый объект в словарь через его метод to_dict()
    data = [review.to_dict() for review in reviews]

    # Path(__file__)      -> путь к текущему скрипту
    # .resolve().parent   -> папка, где лежит скрипт
    # Так файл создастся рядом с кодом, а не в случайном месте
    file_path = Path(__file__).resolve().parent / filename

    with open(file_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=4)


# ============================================================
# ТОЧКА ВХОДА: код ниже выполняется только при запуске файла:
#     python review.py
# Если файл импортируют из другого скрипта — этот код НЕ выполнится.
# ============================================================
if __name__ == "__main__":
    # Создаём ОБЪЕКТЫ (экземпляры) класса Review.
    # В этот момент автоматически вызывается метод __init__
    review_1 = Review("Отличный товар, рекомендую!", 5, "Анна")
    review_2 = Review("Так себе, качество слабое.", 2, "Иван")
    review_3 = Review("Нормально, за свою цену ок.", 3, "Мария")

    # Печатаем объекты — сработает метод __repr__
    print(review_1)
    print(review_2)
    print()

    # Обращаемся к АТРИБУТАМ объекта через точку
    print(f"Автор первого отзыва: {review_1.author}")
    print(f"Рейтинг первого отзыва: {review_1.rating}")
    print()

    # Вызываем МЕТОД объекта
    print("Словарь из первого отзыва:", review_1.to_dict())
    print()

    # Собираем объекты в список (как в День 2)
    reviews = [review_1, review_2, review_3]

    # Проходим по всем отзывам и печатаем их в виде словарей
    for review in reviews:
        print(review.to_dict())

    # Сохраняем всё в JSON
    save_reviews_to_json(reviews)
    print("\nОтзывы сохранены в reviews.json")